"""Pinned factual EMS-ESP reference metadata. No upstream executable driver code."""
import csv
import gzip
import io
import hashlib
import json
from pathlib import Path
import sys

ROOT=Path(__file__).resolve().parents[1]

def generate(check=False):
    base=ROOT/'public/ems'
    for name,source in json.loads((base/'SOURCES.json').read_text())['sources'].items():
        assert hashlib.sha256((base/name).read_bytes()).hexdigest()==source['sha256'], name
    rows=list(csv.DictReader(io.StringIO((base/'entities.csv').read_text())))
    specs=[];index={};groups={}
    for row in rows:
        kind=row['device type'];product=int(row['product id'])
        assert 0<=product<=255
        assert row['writeable'] in ('true','false')
        spec=[row[k].strip() for k in ('shortname','fullname','type [options...] \\| (min/max)','uom')]+[row['writeable']=='true']
        signature=json.dumps(spec,separators=(',',':'))
        if signature not in index:index[signature]=len(specs);specs.append(spec)
        key=f'{kind}:{product}'
        group=groups.setdefault(key,{'name':row['device name'],'fields':[]})
        assert group['name']==row['device name']
        group['fields'].append(index[signature])
    telegrams={}
    for row in csv.DictReader(io.StringIO((base/'telegrams.csv').read_text())):
        type_id=int(row['telegram_type_id'],16);assert 0<=type_id<=65535
        telegrams.setdefault(type_id,[])
        if row['name'] not in telegrams[type_id]:telegrams[type_id].append(row['name'])
    def types(value):
        parts=value.split('-')
        lo=int(parts[0],16);hi=int(parts[-1],16)
        assert 0<=lo<=hi<=65535 and hi-lo<32
        return range(lo,hi+1)
    library={};library_fields=[]
    library_rows=list(csv.DictReader(io.StringIO((base/'library.csv').read_text())))
    for row in library_rows:
        field=[row[k] for k in ('Offset','Variable_Name','Min','Max','Resolution','Unit','Comment')]
        index=len(library_fields);library_fields.append(field)
        for type_id in types(row['Telegram_ID']):library.setdefault(type_id,[]).append(index)
    metadata={}
    for key,entry in json.loads((base/'telegram-metadata.json').read_text()).items():
        for type_id in types(key):
            metadata[type_id]=entry
            telegrams.setdefault(type_id,[entry['name']])
    devices=json.loads((base/'devices.json').read_text())
    boiler_names={}
    for model in json.loads((ROOT/'public/boilers/catalog-v1.json').read_text())['models']:
        if not model.get('selectable'):continue
        for source in model.get('source_entries',[]):
            if source.startswith('emsesp-product-'):
                key=source.removeprefix('emsesp-product-')
                values=boiler_names.setdefault(key,{}).setdefault(model['brand'],[])
                if model['name'] not in values:values.append(model['name'])
    data={'boilerNames':boiler_names,'library' :library,'libraryFields':library_fields,'telegramMetadata':metadata,'entities':specs,'groups':groups,'devices':devices,'telegrams':{k:' / '.join(v) for k,v in telegrams.items()}}
    payload=('window.OT_EMS_REFERENCE = '+json.dumps(data,ensure_ascii=True,separators=(',',':'))+';\n').encode()
    compressed=io.BytesIO()
    with gzip.GzipFile(fileobj=compressed,mode='wb',filename='',mtime=0,compresslevel=9) as stream:
        stream.write(payload)
    asset=ROOT/'data/html/ems-reference.js.gz'
    if check:
        # Gzip output can differ across zlib versions. Verify the exact content,
        # fixed timestamp and original generated bytes supplied to the firmware.
        raw=asset.read_bytes()
        assert raw[:3]==b'\x1f\x8b\x08' and raw[4:8]==b'\0'*4
        assert gzip.decompress(raw)==payload, 'Regenerate EMS reference asset'
    else:asset.write_bytes(compressed.getvalue())
    # The device UI needs identification and metadata for decoded fields only.
    # Preserve the full factual reference above for offline use, not a second UI
    # catalogue of unrelated equipment or a second source of measured values.
    aliases=json.loads((base/'e32-field-aliases.json').read_text())
    wanted=set(aliases.values());compact_specs=[];compact_index={};compact_groups={}
    for key,group in groups.items():
        if not key.startswith('boiler:'):continue
        selected=[]
        for index in group['fields']:
            spec=specs[index]
            if spec[0] not in wanted:continue
            signature=json.dumps(spec,separators=(',',':'))
            if signature not in compact_index:
                compact_index[signature]=len(compact_specs);compact_specs.append(spec)
            selected.append(compact_index[signature])
        compact_groups[key]={'name':group['name'],'fields':selected}
    compact={'aliases':aliases,'devices':devices,'boilerNames':boiler_names,
             'entities':compact_specs,'groups':compact_groups}
    compact_asset=ROOT/'data/html/ems-metadata.js'
    compact_payload='window.OT_EMS_METADATA = '+json.dumps(compact,separators=(',',':'))+';\n'
    if check:assert compact_asset.read_text()==compact_payload,'Regenerate EMS device metadata'
    else:compact_asset.write_text(compact_payload)
    h=['#pragma once','#include <cstdint>','namespace heating::ems {','inline const char* telegramName(uint16_t type) {','    switch(type) {']
    for key,names in sorted(telegrams.items()):
        h.append(f'    case {key}: return '+json.dumps(' / '.join(names))+';')
    h+=['    default: return "Unknown";','    }','}',
        'inline const char* addressRole(uint8_t address) {',
        '    switch(address & 0x7F) {',
        '    case 0: return "All"; case 8: return "Boiler";',
        '    case 0x10: case 0x17: return "Thermostat";',
        '    case 0x0B: return "Service"; default: return "Device";',
        '    }','}','}']
    for file,content in [(ROOT/'src/EMS/EmsReference.h','\n'.join(h)+'\n')]:
        if check:assert file.read_text()==content, f'Regenerate {file}'
        else:file.write_text(content)
    print(f'PASS EMS reference: {len(rows)} entity rows, {len(groups)} groups, {len(telegrams)} telegram IDs, {len(devices)} device records, {len(library_rows)} offset definitions; metadata only')

if __name__=='__main__':generate('--check' in sys.argv)
