"""Bounded room contact configuration and conservative logical aggregation.

Contact state is logical HA/source context, not a temperature measurement or
physical output permission. Callers preserve original report ages and identity.
"""
from dataclasses import dataclass

MAX_CONTACTS = 8
MAX_AGE_MS = 86400000
MAX_DELAY_MS = 600000
CONTACT_DEVICE_CLASSES = ('window', 'door', 'opening', 'garage_door')


def _integer(value, minimum, maximum):
    return type(value) is int and minimum <= value <= maximum


@dataclass(frozen=True, slots=True)
class ContactPolicy:
    maximum_age_ms: int = 3600000
    open_delay_ms: int = 0
    close_delay_ms: int = 30000

    @classmethod
    def from_dict(cls, value):
        if type(value) is not dict or set(value) != {'maximum_age_ms', 'open_delay_ms', 'close_delay_ms'}:
            raise ValueError('invalid_contact_policy')
        result = cls(**value)
        result.validate()
        return result

    def validate(self):
        if (not _integer(self.maximum_age_ms, 1000, MAX_AGE_MS)
                or not _integer(self.open_delay_ms, 0, MAX_DELAY_MS)
                or not _integer(self.close_delay_ms, 0, MAX_DELAY_MS)
                or max(self.open_delay_ms, self.close_delay_ms) >= self.maximum_age_ms):
            raise ValueError('invalid_contact_policy')

    def as_dict(self):
        self.validate()
        return {key: getattr(self, key) for key in ('maximum_age_ms', 'open_delay_ms', 'close_delay_ms')}


@dataclass(frozen=True, slots=True)
class ContactBinding:
    entity: object
    kind: str

    @classmethod
    def from_dict(cls, value):
        from .v1_model import EntityReference
        if type(value) is not dict or set(value) != {'entity', 'kind'} or value['kind'] not in ('window', 'door'):
            raise ValueError('invalid_contact_binding')
        ref = value['entity']
        if (type(ref) is not dict or set(ref) != {'entity_id', 'platform', 'unique_id'}
                or type(ref['entity_id']) is not str or not ref['entity_id'].startswith('binary_sensor.')
                or not ref['entity_id'].removeprefix('binary_sensor.')
                or len(ref['entity_id']) > 255
                or any(v is not None and (type(v) is not str or not 1 <= len(v) <= 256)
                       for v in (ref['platform'], ref['unique_id']))
                or (ref['platform'] is None) != (ref['unique_id'] is None)):
            raise ValueError('invalid_contact_binding')
        return cls(EntityReference.from_dict(ref), value['kind'])

    def as_dict(self):
        return {'entity': self.entity.as_dict(), 'kind': self.kind}


def contacts_from_dict(value):
    if type(value) is not list or not 0 <= len(value) <= MAX_CONTACTS:
        raise ValueError('invalid_contacts')
    contacts = tuple(ContactBinding.from_dict(row) for row in value)
    identities = [c.entity.identity() for c in contacts]
    entity_ids = [c.entity.entity_id for c in contacts]
    if len(set(identities)) != len(identities) or len(set(entity_ids)) != len(entity_ids):
        raise ValueError('duplicate_contact_binding')
    return contacts


def select_contacts(hass, selections):
    """Resolve the same bounded native selections for the editor and wizard."""
    from homeassistant.helpers import entity_registry as er
    from .v1_heating_graph import selected_reference
    if (type(selections) is not list or len(selections) > MAX_CONTACTS
            or any(type(value) is not str or value.startswith('unresolved:') for value in selections)
            or len(set(selections)) != len(selections)):
        raise ValueError('invalid_contacts')
    result = []
    for selection in selections:
        raw = selected_reference(hass, selection, ('binary_sensor',))
        row = er.async_get(hass).async_get(raw['entity_id'])
        state = hass.states.get(raw['entity_id'])
        kind = ((state.attributes.get('device_class') if state else None)
                or row.device_class or row.original_device_class)
        if kind not in CONTACT_DEVICE_CLASSES:
            raise ValueError('not_contact_sensor')
        result.append({'entity': raw, 'kind': 'door' if kind in ('door', 'garage_door') else 'window'})
    return contacts_from_dict(result)


@dataclass(frozen=True, slots=True)
class ContactSample:
    value: bool | None
    age_ms: int
    # Original identity/report token, never generated by assess() or a timer.
    token: object = None


@dataclass(frozen=True, slots=True)
class ContactAssessment:
    open: bool | None
    age_ms: int
    reason: str
    pending_ms: int = 0


class ContactAggregator:
    """Any open inhibits; all contacts must be valid before closing can resume.

    Delays retain the age of the prior stable proof. Polling cannot renew it.
    Unavailability discards a closed baseline. Reconnects construct a new owner.
    """
    def __init__(self, policy: ContactPolicy):
        policy.validate()
        self.policy = policy
        self._last_now = None
        self._stable = None
        self._stable_origin = None
        self._candidate = None
        self._candidate_since = None

    def reset(self):
        self._stable = self._stable_origin = None
        self._candidate = self._candidate_since = None

    def _unknown(self, reason):
        self.reset()
        return ContactAssessment(None, MAX_AGE_MS, reason)

    def assess(self, now_ms: int, samples: tuple[ContactSample, ...]):
        if not _integer(now_ms, 0, 2**63 - 1):
            return self._unknown('contact_clock_invalid')
        if self._last_now is not None and now_ms < self._last_now:
            self._last_now = now_ms
            return self._unknown('contact_clock_reversed')
        self._last_now = now_ms
        if (type(samples) is not tuple or not 1 <= len(samples) <= MAX_CONTACTS
                or any(type(s) is not ContactSample for s in samples)):
            return self._unknown('contact_state_unknown')
        valid = tuple(s for s in samples if type(s.value) is bool
                      and _integer(s.age_ms, 0, self.policy.maximum_age_ms - 1))
        opens = tuple(s for s in valid if s.value)
        # A received open contact can keep demand paused even if another is lost.
        # A delayed opening may only hold a closed baseline while all are valid.
        if opens:
            desired, age = True, min(s.age_ms for s in opens)
            if len(valid) != len(samples):
                self._stable, self._stable_origin = True, now_ms - age
                self._candidate = self._candidate_since = None
                return ContactAssessment(True, age, 'contact_open')
        elif len(valid) == len(samples):
            desired, age = False, max(s.age_ms for s in valid)
        else:
            return self._unknown('contact_state_unknown')
        origin = now_ms - age
        if self._stable is desired:
            self._stable_origin = origin
            self._candidate = self._candidate_since = None
            return ContactAssessment(desired, age, 'contact_open' if desired else 'contacts_closed')
        delay = self.policy.open_delay_ms if desired else self.policy.close_delay_ms
        if self._candidate is not desired:
            self._candidate, self._candidate_since = desired, now_ms
        remaining = max(0, delay - (now_ms - self._candidate_since))
        if remaining:
            # An absent/expired baseline must never permit heating during debounce.
            stable_age = now_ms - self._stable_origin if self._stable_origin is not None else MAX_AGE_MS
            stable = self._stable if 0 <= stable_age < self.policy.maximum_age_ms else None
            return ContactAssessment(stable, stable_age if stable is not None else MAX_AGE_MS,
                                     'contact_open_delay' if desired else 'contact_close_delay', remaining)
        self._stable, self._stable_origin = desired, origin
        self._candidate = self._candidate_since = None
        return ContactAssessment(desired, age, 'contact_open' if desired else 'contacts_closed')


def comfort_record(room):
    """Wire projection contains aggregate context policy, never native entity IDs."""
    if room.comfort is None:
        return None
    result = {**room.comfort, 'minimum_centi_c': room.minimum_target_centi_c,
              'maximum_centi_c': room.maximum_target_centi_c,
              'window': room.window is not None or bool(room.contacts),
              'presence': room.presence is not None}
    if room.contacts:
        result['window_max_age_ms'] = room.contact_policy.maximum_age_ms
    return result


def context_record(room):
    if room.comfort is not None:
        return {'comfort': comfort_record(room)}
    if room.contacts:
        return {'contacts': {'maximum_age_ms': room.contact_policy.maximum_age_ms}}
    return {}
