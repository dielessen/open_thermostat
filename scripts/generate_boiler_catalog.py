"""Generate the small offline display catalog; public metadata never enables EMS control."""
from pathlib import Path
import argparse
import json
import re
from urllib.parse import urlsplit

ROOT = Path(__file__).resolve().parents[1]
START = '    // BEGIN GENERATED BOILER CATALOG\n'
END = '    // END GENERATED BOILER CATALOG\n'


def generate(check=False):
    catalog = json.loads((ROOT / 'public/boilers/catalog-v1.json').read_text())
    assert catalog['schema'] == 1 and catalog['purpose'] == 'presentation_catalog_only'
    assert catalog['control_profiles'] is False
    models = catalog['models']
    assert len({m['id'] for m in models}) == len(models)
    for m in models:
        assert re.fullmatch(r'[a-z0-9-]{1,63}', m['id'])
        assert 0 < len(m['name']) < 200
        if m['image']:
            image = urlsplit(m['image'])
            allowed = {
                'www.nefit-bosch.nl': '/media/country_pool/professioneel/productafbeeldingen/',
                'www.bosch-homecomfort.com': '/us/media/country_pool/service_support/discontinued-products/',
                'bbqkees-electronics.nl': '/wp-content/uploads/ems-devices/nefit/boilers/',
            }
            assert image.scheme == 'https' and not image.username and not image.password
            assert image.netloc in allowed and image.path.startswith(allowed[image.netloc])
            assert not image.query and not image.fragment
            proof = m['image_provenance']
            assert proof['url'] == m['image'] and proof['depicted_model'] and proof['scope']
            assert re.fullmatch('[0-9a-f]{64}', proof['sha256_at_review'])
            page = urlsplit(proof['source_page'])
            assert page.scheme == 'https' and page.netloc == image.netloc
    compact = []
    for m in models:
        entry = {k: m[k] for k in ('id', 'name', 'kind', 'image')}
        if m['image']:
            entry['imageSource'] = m['image_provenance']['source_page']
            entry['imageCredit'] = m['image_provenance']['publisher']
            entry['imageModel'] = m['image_provenance']['depicted_model']
        compact.append(entry)
    js = ROOT / 'data/html/boiler-display.js'
    source = js.read_text()
    assert source.count(START) == source.count(END) == 1
    before, tail = source.split(START)
    _, after = tail.split(END)
    generated = '    const catalog = ' + json.dumps(compact, ensure_ascii=True, separators=(',', ':')) + ';\n'
    header = '#pragma once\n#include <string_view>\n\n// Generated by scripts/generate_boiler_catalog.py. Presentation only.\nnamespace heating {\ninline constexpr std::string_view boilerDisplayModelIds[] = {\n'
    header += ''.join('    ' + json.dumps(m['id']) + ',\n' for m in models)
    header += '};\n}\n'
    for path, data in [(js, before + START + generated + END + after), (ROOT / 'src/BoilerDisplayModels.h', header)]:
        if check:
            assert path.read_text() == data, f'Regenerate catalog: {path.relative_to(ROOT)}'
        else:
            path.write_text(data)
    print(f'PASS offline catalog: {len(models)} selections, exact browser/firmware IDs; public images only')


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    generate(parser.parse_args().check)
